/**
 * 
 * 力扣45跳跃游戏2
 * 中等
 * 贪心
 * 
 * 
 * 
 * 给定一个长度为 n 的 0 索引整数数组 nums。初始位置为 nums[0]。
 * 每个元素 nums[i] 表示从索引 i 向前跳转的最大长度。换句话说，如果你在 nums[i] 处，你可以跳转到任意位置 j，其中 i <= j < i + nums[i]。
 * 请你返回最少的跳跃次数，使得你可以到达 nums[n - 1]。
 * 
 * 思路：
 * 
 * 这个我想到了个，问题，就是这个反向跳跃的思想，我好像理解一点了，其实我的疑惑就是为啥最远的那个点他的跳跃方案总是可行的，我在担心这个，
 * 于是我举例看了一下，假设此时最远处的右侧有一个跳跃点，他是真正的可行方案，那么他的前一个点要么在最远点的左侧，要么在右侧，如果在右侧，他
 * 就选取右侧的一个点作为新的点，那这样其实还是转换成了最远点和右侧点的问题， 那就剩下左侧了，如果在最远点的左侧，此时如果这个左侧的点能跳跃到
 * 上一个点的话，那他肯定是能直接跨越最远点来跳跃的，说明他肯定能到达最远点，所有最远点一定存在一个跳跃方案，对吗？
 * 
 * 
 * 你的直觉和推导核心完全正确。这就是算法导论里最经典的**贪心替换证明（Greedy Exchange Property）**。

把你的逻辑整理得更严密一点，就是以下两步：

**1. 设定场景**

* 假设终点是 `target`。
* 贪心策略选中的点是 $A$（即所有能跳到 `target` 的点中，下标最小、最靠左的那个）。
* 假设理论上存在某条**真正可行的完整最优路径**，它在这一步选的是点 $B$，并且 $B$ 在 $A$ 的右侧（$A < B < target$）。

**2. 考察最优路径中 $B$ 的前驱节点 $P$**

* **情况一：$P$ 也在 $A$ 的右侧（$A < P < B$）**
* 这意味着从起点一路跳过来的链条上，必然存在某一步是从“$\le A$ 的区域”跨越到了“$> A$ 的区域”。这依然会落到情况二。


* **情况二：$P$ 在 $A$ 的左侧或正好是 $A$（$P \le A$）**
* 既然 $P$ 能一步跳到更远处的 $B$（即 $P + nums[P] \ge B$），而 $A$ 位于 $P$ 和 $B$ 之间（$P \le A < B$），那么从 $P$ 出发**必定也能覆盖到 $A$**（$P + nums[P] \ge A$）。
* 这意味着，你完全可以把原本跳向 $B$ 的这一步，直接“改道”换成跳向 $A$：

$$\text{原路径: } \dots \to P \to B \to target$$


$$\text{替换后: } \dots \to P \to A \to target$$





因为 $A$ 本身就能一步跳到 $target$，替换后整条路径依然完全合法，步数也没有增加。

这就直接证明了：**任何经过右侧点 $B$ 的可行方案，都可以无损地替换为经过最左侧点 $A$**。选最左侧的点绝不会把路走死，必定有一条通往起点的路径可达。
 */


class Solution {
    public int jump(int[] nums) {
        int n = nums.length;
        int step = 0;
        int target = n -1;
        while(target > 0){
            for(int i =0;i<target;i++){
                if(i + nums[i] >= target){
                    step++;
                    target = i;
                    break;
                }
            }
        }
        return step;
    }
}