/**
 * 
 * 力扣763划分字母区间
 * 中等
 * 贪心
 * 给定一个字符串 s ，将该字符串划分成尽可能多的片段，同一字母最多出现在一个片段中。返回一个表示每个字符串片段的长度的列表。
 * 
 * 
 * 思路：
 * 
 * 这道题整体的思路是使用下标来记录每个字符串，使用字符的末尾下标判断已经维护的字符串和下标的关系来确定这个字符是否需要被拆分
 * ，一个最简单的例子，你维护了一个字符串此时他的末尾下标大于此时遍历的下标i，那就需要继续往后了，因为此时此时如果分割的话，这个字
 * 符也还是会出现在其他的字符串内，不满足的，同时维护一个end就够了
 * 
 * 你的理解完全正确，且抓住了这道贪心算法的核心本质。核心逻辑拆解约束条件：同一个字母只能出现在同一个片段里。这意味着片段的结束位
 * 置至少要覆盖该片段内所有已出现字符的最大末尾下标。边界推演（贪心）：遍历字符时，如果当前字符的最后出现位置比当前维护的边界 end 
 * 还要远，就必须把边界向右推：end = Math.max(end, last[c])。只要当前遍历下标 $i < end$，就说明前面出现的某些字符在后面还会冒出
 * 来，此时绝对不能切分。只有当遍历到达 $i == end$ 时，才说明当前片段包含的所有字符在后面都不会再出现了，此时立即切分就是能保证片段数
 * 量最多的贪心最优解。
 * 
 * 
 * 
 * 
 */


class Solution {
    public List<Integer> partitionLabels(String s) {
        int[] hash = new int[26];
        for(int i = 0;i<s.length();i++){
            char c =s.charAt(i);
            hash[c - 'a']=i;
        }
        //贪心逻辑
        List<Integer> ans = new ArrayList<>();
        int end = 0,start = 0;
        for(int i=0;i<s.length();i++){
            int index = s.charAt(i) - 'a';
            end = Math.max(end,hash[index]);
            if(end<=i){
                ans.add(end - start+1);
                start = end +1;
            }
        }
        return ans;
    }
}